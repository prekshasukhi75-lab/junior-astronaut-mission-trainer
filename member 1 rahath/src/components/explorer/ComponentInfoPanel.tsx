import { ExternalLink, Info, Sparkles } from 'lucide-react';
import { VERIFIED_NASA_SOURCES } from '../../data/imageExplorerData';
import type {
  AnalyzedImageResult,
  DetectedComponent,
  NasaImageItem,
} from '../../types/imageExplorer';

interface ComponentInfoPanelProps {
  image: NasaImageItem;
  analysisResult: AnalyzedImageResult | null;
  selectedComponent: DetectedComponent | null;
}

export function ComponentInfoPanel({
  image,
  analysisResult,
  selectedComponent,
}: ComponentInfoPanelProps) {
  return (
    <div className="space-y-6">
      {/* AI Component Discovery Card (Clearly Separated from NASA Official Metadata) */}
      {selectedComponent ? (
        <article className="rounded-xl border border-cyan-500/40 bg-[#0B1120] p-6">
          <div className="flex flex-wrap items-center justify-between gap-2 text-xs">
            <span className="inline-flex items-center gap-1.5 font-mono text-cyan-300">
              <Sparkles className="h-3.5 w-3.5" aria-hidden="true" />
              <span>AI Component Discovery</span>
            </span>
            <span className="font-mono text-slate-400">
              Confidence: {selectedComponent.confidence}
            </span>
          </div>

          <h3 className="mt-2 font-display text-2xl font-bold text-white">
            {selectedComponent.name}
          </h3>

          <p className="mt-2.5 text-base leading-relaxed text-slate-100">
            {selectedComponent.simpleDescription}
          </p>

          <div className="mt-5 grid grid-cols-1 gap-4 border-t border-slate-800/80 pt-5 md:grid-cols-2">
            <div>
              <h4 className="font-mono text-xs text-cyan-300">
                Science Explanation (Ages 7–12)
              </h4>
              <p className="mt-1.5 text-sm leading-relaxed text-slate-300">
                {selectedComponent.scientificExplanation}
              </p>
            </div>

            <div>
              <h4 className="font-mono text-xs text-cyan-300">Interesting Fact</h4>
              <p className="mt-1.5 text-sm leading-relaxed text-slate-300">
                {selectedComponent.interestingFact}
              </p>
            </div>
          </div>

          <div className="mt-4 flex items-start gap-2 rounded-lg border border-slate-800 bg-[#060913] p-3.5 text-xs leading-relaxed text-slate-300">
            <Info className="mt-0.5 h-4 w-4 shrink-0 text-cyan-400" aria-hidden="true" />
            <span>
              <strong>Evidence &amp; AI Distinction:</strong> {selectedComponent.evidenceNote}{' '}
              This explanation was generated by AI vision analysis and is separate from the
              official NASA caption below.
            </span>
          </div>
        </article>
      ) : analysisResult?.summary ? (
        <article className="rounded-xl border border-slate-800/90 bg-[#0B1120] p-6">
          <p className="font-mono text-xs text-cyan-300">
            AI Vision Overview · Select a Highlighted Region Above
          </p>
          <h3 className="mt-1.5 font-display text-xl font-bold text-white">
            {analysisResult.subject}
          </h3>
          <p className="mt-2 text-sm leading-relaxed text-slate-200">
            {analysisResult.summary}
          </p>
        </article>
      ) : null}

      {/* Official NASA Metadata & Source Attribution */}
      <article className="rounded-xl border border-slate-800/90 bg-[#0B1120] p-6">
        <div className="flex flex-wrap items-center justify-between gap-2">
          <p className="font-mono text-xs text-slate-400">
            Official NASA Image &amp; Video Library Record
          </p>
          <span className="font-mono text-xs text-cyan-300">
            NASA ID: {image.nasaId}
          </span>
        </div>

        <h3 className="mt-2 font-display text-xl font-bold text-white">
          {image.title}
        </h3>

        <div className="mt-2 flex flex-wrap items-center gap-x-3 gap-y-1 text-xs text-slate-400">
          <span>Source Attribution: {image.center || 'NASA Archive'}</span>
          {image.dateCreated && (
            <>
              <span aria-hidden="true">·</span>
              <span>Date: {image.dateCreated.slice(0, 10)}</span>
            </>
          )}
          {image.photographer && (
            <>
              <span aria-hidden="true">·</span>
              <span>Credit: {image.photographer}</span>
            </>
          )}
        </div>

        <p className="mt-4 text-sm leading-relaxed text-slate-300">
          {image.description}
        </p>

        {image.keywords.length > 0 && (
          <p className="mt-4 font-mono text-xs text-slate-400">
            Keywords: {image.keywords.slice(0, 8).join(' · ')}
          </p>
        )}

        <div className="mt-5 flex flex-wrap items-center gap-3 border-t border-slate-800/80 pt-4">
          <a
            href={image.nasaSourceUrl}
            target="_blank"
            rel="noopener noreferrer"
            className="inline-flex min-h-[40px] items-center gap-2 rounded-md border border-slate-700 bg-[#111B33] px-3.5 py-2 text-xs font-semibold text-white transition-colors hover:border-cyan-400/70 hover:text-cyan-200"
          >
            <span>Open Original NASA Source</span>
            <ExternalLink className="h-3.5 w-3.5" aria-hidden="true" />
          </a>

          {VERIFIED_NASA_SOURCES.map((source) => (
            <a
              key={source.url}
              href={source.url}
              target="_blank"
              rel="noopener noreferrer"
              className="inline-flex min-h-[38px] items-center gap-1.5 text-xs font-medium text-slate-300 underline-offset-4 hover:text-cyan-300 hover:underline"
            >
              <span>{source.label}</span>
              <ExternalLink className="h-3 w-3" aria-hidden="true" />
            </a>
          ))}
        </div>
      </article>
    </div>
  );
}
